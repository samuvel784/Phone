package com.example.util

import com.example.model.CallRecord
import java.io.ByteArrayOutputStream

/**
 * Builds portable export files (CSV and a minimal dependency-free PDF) from the
 * call history. The PDF writer hand-rolls a tiny PDF 1.4 document (Helvetica
 * text only) so no third-party library is required.
 */
object CallLogExport {

    private fun csvEscape(field: String): String {
        val needsQuoting = field.contains(',') || field.contains('"') || field.contains('\n') || field.contains('\r')
        return if (needsQuoting) "\"" + field.replace("\"", "\"\"") + "\"" else field
    }

    /** Builds a UTF-8 CSV document of the call history. */
    fun buildCallLogCsv(records: List<CallRecord>): String {
        val sb = StringBuilder()
        sb.append("Date,Name,Number,Label,Type,DurationSec,SimSlot\n")
        for (r in records) {
            sb.append(csvEscape(r.timestamp)).append(',')
            sb.append(csvEscape(r.name)).append(',')
            sb.append(csvEscape(r.number)).append(',')
            sb.append(csvEscape(r.label)).append(',')
            sb.append(r.type.name).append(',')
            sb.append(r.duration).append(',')
            sb.append(r.simSlot)
            sb.append('\n')
        }
        return sb.toString()
    }

    private fun pdfEscape(s: String): String {
        val escaped = s.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")
        val sb = StringBuilder(escaped.length)
        for (ch in escaped) {
            val c = ch.code
            if (c in 32..126 || c in 160..255) sb.append(ch) else sb.append('?')
        }
        return sb.toString()
    }

    /** Builds a paginated PDF 1.4 document of the call history (Latin-1 text). */
    fun buildCallLogPdf(records: List<CallRecord>, title: String, exportedAt: String): ByteArray {
        val linesPerPage = 50
        val headerLine = "Date & Time  |  Name  |  Number  |  Type  |  Duration (s)  |  SIM"
        val contentLines = records.map { r ->
            "${r.timestamp} | ${r.name} | ${r.number} | ${r.type.name} | ${r.duration} | ${r.simSlot}"
        }

        val pages: MutableList<List<String>> = mutableListOf()
        val headerBlock = listOf(title, "Generated by NovaDial - Exported: $exportedAt", "")
        if (contentLines.isEmpty()) {
            pages.add(headerBlock + listOf(headerLine, "(no call records)"))
        } else {
            var current = headerBlock.toMutableList()
            current.add(headerLine)
            for (line in contentLines) {
                current.add(line)
                if (current.size >= linesPerPage) {
                    pages.add(current)
                    current = mutableListOf()
                }
            }
            if (current.isNotEmpty()) pages.add(current)
        }

        // Objects: 1 catalog, 2 pages tree, 3 font, then 2 per page (page + content stream)
        val objCount = 3 + 2 * pages.size
        val out = ByteArrayOutputStream()
        val offsets = IntArray(objCount + 1)

        fun write(s: String) {
            out.write(s.toByteArray(Charsets.ISO_8859_1))
        }

        write("%PDF-1.4\n")
        write("%\u00E2\u00E3\u00CF\u00D3\n")

        offsets[1] = out.size()
        write("1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n")

        offsets[2] = out.size()
        val kids = pages.indices.joinToString(" ") { "${4 + it * 2} 0 R" }
        write("2 0 obj\n<< /Type /Pages /Kids [$kids] /Count ${pages.size} >>\nendobj\n")

        offsets[3] = out.size()
        write("3 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>\nendobj\n")

        for ((i, lines) in pages.withIndex()) {
            val pageObj = 4 + i * 2
            val contentObj = pageObj + 1

            val contentStream = buildString {
                append("BT /F1 10 Tf 45 740 Td 14 TL\n")
                for ((j, line) in lines.withIndex()) {
                    append("(${pdfEscape(line)}) Tj\n")
                    if (j < lines.size - 1) append("T*\n")
                }
                append("ET")
            }

            offsets[pageObj] = out.size()
            write("$pageObj 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 3 0 R >> >> /Contents $contentObj 0 R >>\nendobj\n")

            offsets[contentObj] = out.size()
            val len = contentStream.toByteArray(Charsets.ISO_8859_1).size
            write("$contentObj 0 obj\n<< /Length $len >>\nstream\n$contentStream\nendstream\nendobj\n")
        }

        val xrefOffset = out.size()
        write("xref\n0 ${objCount + 1}\n")
        write("0000000000 65535 f \n")
        for (i in 1..objCount) {
            write(offsets[i].toString().padStart(10, '0') + " 00000 n \n")
        }
        write("trailer\n<< /Size ${objCount + 1} /Root 1 0 R >>\nstartxref\n$xrefOffset\n%%EOF")

        return out.toByteArray()
    }
}